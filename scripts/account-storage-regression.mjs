import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import ts from 'typescript';
const source = await readFile('src/lib/account-storage.ts','utf8');
const data = new Map([['draft','legacy private content']]);
const localStorage={getItem:key=>data.get(key)??null,setItem:(key,value)=>data.set(key,value),removeItem:key=>data.delete(key)};
const context={exports:{},window:{localStorage}};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,context);
const {accountStorage,setActiveStorageUser}=context.exports;
assert.equal(accountStorage.getItem('draft'),null);
assert.equal(accountStorage.setItem('draft','anonymous'),false);
setActiveStorageUser('user-a');
assert.equal(accountStorage.getItem('draft'),null);
assert.equal(accountStorage.setItem('draft','private-a'),true);
setActiveStorageUser('user-b');
assert.equal(accountStorage.getItem('draft'),null);
accountStorage.setItem('draft','private-b');
setActiveStorageUser('user-a');
assert.equal(accountStorage.getItem('draft'),'private-a');
accountStorage.removeItem('draft');
assert.equal(accountStorage.getItem('draft'),null);
setActiveStorageUser('user-b');
assert.equal(accountStorage.getItem('draft'),'private-b');
localStorage.setItem=()=>{throw new Error('quota exceeded');};
assert.equal(accountStorage.setItem('draft','lost'),false);
setActiveStorageUser(null);
assert.equal(accountStorage.getItem('draft'),null);
assert.equal(data.get('draft'),'legacy private content');
console.log('Account storage regression passed: 11 assertions covering account switching, legacy isolation, logout and storage failure.');
